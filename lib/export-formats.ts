/**
 * 카드를 GitHub에 바로 커밋 가능한 포맷으로 내보낸다.
 *
 *   1) toStandaloneHtml — 스타일·폰트 인라인된 단독 HTML. 그대로 /cards/foo.html
 *      로 커밋하면 GitHub Pages에서 렌더됨.
 *   2) toMarkdown       — GitHub Flavored Markdown. README나 /docs/*.md에 붙여넣기.
 */

import type { EditorialCardData } from "./types";

// ---------------------------------------------------------------------------
// 안전한 HTML escape
// ---------------------------------------------------------------------------

function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// ---------------------------------------------------------------------------
// 안전한 파일명 생성
// ---------------------------------------------------------------------------

export function suggestFilename(card: EditorialCardData, ext: "html" | "md"): string {
  const base = (card.headline || "folio-card")
    .toLowerCase()
    .replace(/[^a-z0-9가-힣]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  const date = card.fetchedAt.slice(0, 10);
  return `${date}-${base || "card"}.${ext}`;
}

// ---------------------------------------------------------------------------
// Markdown 내보내기
// ---------------------------------------------------------------------------

export function toMarkdown(card: EditorialCardData): string {
  const lines: string[] = [];
  const date = card.fetchedAt.slice(0, 10);

  // YAML frontmatter (Jekyll/Hugo/Astro 호환)
  lines.push("---");
  lines.push(`title: "${card.headline.replace(/"/g, '\\"')}"`);
  lines.push(`description: "${card.dek.replace(/"/g, '\\"').slice(0, 200)}"`);
  lines.push(`date: ${date}`);
  lines.push(`source: ${card.sourceUrl}`);
  if (card.sourceSiteName) lines.push(`site: "${card.sourceSiteName}"`);
  lines.push(`category: "${card.eyebrow}"`);
  if (card.heroImage) lines.push(`image: ${card.heroImage}`);
  lines.push("---");
  lines.push("");

  // 카테고리 · 키커
  lines.push(`**${card.eyebrow}**${card.kicker ? ` · ${card.kicker}` : ""}`);
  lines.push("");

  // 헤드라인
  lines.push(`# ${card.headline}`);
  lines.push("");

  // 데크
  if (card.dek) {
    lines.push(`> *${card.dek}*`);
    lines.push("");
  }

  // 히어로 이미지
  if (card.heroImage) {
    lines.push(`![${esc(card.headline)}](${card.heroImage})`);
    lines.push("");
  }

  // By line
  lines.push(`— **${card.sourceSiteName ?? card.sourceDomain}**`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // 리드
  lines.push(card.lead);
  lines.push("");

  // 본문
  for (const p of card.bodyParagraphs) {
    lines.push(p);
    lines.push("");
  }

  // 풀쿼트
  if (card.pullQuote) {
    lines.push(`> ## "${card.pullQuote}"`);
    lines.push(`> — ${card.sourceSiteName ?? card.sourceDomain}`);
    lines.push("");
  }

  // 핵심 포인트
  if (card.keyPoints.length > 0) {
    const isKo = card.lang === "ko" || card.lang === "mixed";
    lines.push(`### ${isKo ? "핵심 메모" : "Field Notes"}`);
    lines.push("");
    card.keyPoints.forEach((k, i) => {
      lines.push(`${i + 1}. ${k}`);
    });
    lines.push("");
  }

  // Footer
  lines.push("---");
  lines.push("");
  lines.push(`↳ Source: [${card.sourceDomain}](${card.sourceUrl})`);
  lines.push(`· Composed: ${date}`);
  lines.push("· _Generated by [Folio Cards](https://github.com/seong-ro/nest-alum1) — deterministic editorial card compositor._");
  lines.push("");

  return lines.join("\n");
}

