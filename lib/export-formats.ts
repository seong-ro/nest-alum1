function deriveIssue(iso: string): string {
  const d = new Date(iso);
  const dayOfYear = Math.floor(
    (d.getTime() - new Date(d.getFullYear(), 0, 0).getTime()) /
      (1000 * 60 * 60 * 24),
  );
  return `${String(d.getFullYear()).slice(2)}·${String(dayOfYear).padStart(3, "0")}`;
}

function formatDate(iso: string, ko: boolean): string {
  const d = new Date(iso);
  if (ko) return `${d.getFullYear()}년 ${d.getMonth() + 1}월 ${d.getDate()}일`;
  return d.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

